def get_syntax_tag_rule(tag_name: str) -> dict:
    return SYNTAX_TAG_RULES.get(tag_name, {
        "category": "기타",
        "grammar_level": "상위 문법",
        "difficulty": "어려운 문법",
        "style_role": "미정의 문법",
    })


def get_concept_tag_rule(tag_name: str) -> dict:
    return CONCEPT_TAG_RULES.get(tag_name, {
        "category": "기타",
        "concept_level": "복잡 구조",
        "difficulty": "어려운 구조",
        "style_role": "미정의 구조",
    })


def enrich_syntax_tag(tag_item: dict) -> dict:
    tag_name = tag_item.get("tag", "")
    rule = get_syntax_tag_rule(tag_name)
    return {
        **tag_item,
        **rule,
    }


def enrich_concept_tag(tag_item: dict) -> dict:
    tag_name = tag_item.get("tag", "")
    rule = get_concept_tag_rule(tag_name)
    return {
        **tag_item,
        **rule,
    }